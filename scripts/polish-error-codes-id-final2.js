function normalizeText(text) {
  let value = String(text || '');

  for (const [pattern, replacement] of replacements) {
    value = value.replace(pattern, replacement);
  }

  return value
    .replace(/,([A-Za-z])/g, ', $1')
    .replace(/\(\s+/g, '(')
    .replace(/\s+\)/g, ')')
    .replace(/ {2,}/g, ' ')
    .replace(/\n /g, '\n')
    .replace(/\bMasalah: ([a-z])/g, (_, c) => `Masalah: ${c.toUpperCase()}`)
    .replace(/\bDiagnosis teknisi: ([a-z])/g, (_, c) => `Diagnosis teknisi: ${c.toUpperCase()}`)
    .trim();
}

const content = fs.readFileSync(filePath, 'utf8').replace(/^\uFEFF/, '');
const output = [];
let changed = 0;
let invalidRows = 0;

content.split(/\r?\n/).forEach((line, index) => {
  const trimmed = line.trim();
  if (!trimmed) return;

  try {
    const entry = JSON.parse(trimmed);
    const before = entry.text;
    entry.text = normalizeText(entry.text);
    if (entry.text !== before) changed += 1;
    output.push(JSON.stringify(entry));
  } catch (error) {
    invalidRows += 1;
    throw new Error(`Invalid JSONL row ${index + 1}: ${error.message}`);
  }
});

fs.writeFileSync(filePath, `${output.join('\n')}\n`, 'utf8');

